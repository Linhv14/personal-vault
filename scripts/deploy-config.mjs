import { parse, stringify } from "smol-toml";

export const DEFAULT_DEPLOY_OPTIONS = Object.freeze({
  registrationMode: "token",
  customDomain: null,
  emailFrom: null,
  emailProvider: "resend",
});

const EMAIL_PROVIDERS = ["resend", "cloudflare"];
const HOSTNAME = /^(?=.{1,253}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;
const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

function clearable(value) {
  return value === "none" ? null : value;
}

export function parseDeployFlags(argv) {
  const flags = {};
  for (let index = 0; index < argv.length; index++) {
    const flag = argv[index];
    const takeValue = () => {
      const value = argv[++index];
      if (value === undefined || value.startsWith("--")) throw new Error(`${flag} needs a value`);
      return value;
    };

    switch (flag) {
      case "--open-registration":
        flags.registrationMode = "open";
        break;
      case "--token-registration":
        flags.registrationMode = "token";
        break;
      case "--domain": {
        const domain = clearable(takeValue().toLowerCase());
        if (domain && !HOSTNAME.test(domain)) throw new Error(`Not a hostname: ${domain}`);
        flags.customDomain = domain;
        break;
      }
      case "--email-from": {
        const address = clearable(takeValue());
        if (address && !EMAIL.test(address)) throw new Error(`Not an email address: ${address}`);
        flags.emailFrom = address;
        break;
      }
      case "--email-provider": {
        const provider = takeValue();
        if (!EMAIL_PROVIDERS.includes(provider)) {
          throw new Error(`--email-provider must be one of: ${EMAIL_PROVIDERS.join(", ")}`);
        }
        flags.emailProvider = provider;
        break;
      }
      default:
        throw new Error(`Unknown option: ${flag}`);
    }
  }
  return flags;
}

export function resolveDeployOptions(saved = {}, flags = {}) {
  const known = Object.fromEntries(
    Object.keys(DEFAULT_DEPLOY_OPTIONS)
      .filter((key) => saved[key] !== undefined)
      .map((key) => [key, saved[key]]),
  );
  return { ...DEFAULT_DEPLOY_OPTIONS, ...known, ...flags };
}

export function requiredSecrets(options) {
  const secrets = ["REGISTRATION_TOKEN", "EMAIL_PROBE_SECRET", "AT_REST_SECRET"];
  if (options.emailFrom && options.emailProvider === "resend") secrets.push("RESEND_API_KEY");
  return secrets;
}

export function renderConfig(template, { accountId, databaseId, options }) {
  const config = parse(template);
  const database = config.d1_databases?.find((binding) => binding.binding === "DB");
  if (!database) throw new Error('wrangler.toml has no D1 binding named "DB"');

  database.database_id = databaseId;
  config.account_id = accountId;
  config.vars = { ...config.vars, REGISTRATION_MODE: options.registrationMode };

  if (options.customDomain) {
    config.routes = [{ pattern: options.customDomain, custom_domain: true }];
    config.workers_dev = true;
  }
  if (options.emailFrom) {
    config.vars.EMAIL_FROM = options.emailFrom;
    if (options.emailProvider === "cloudflare") config.send_email = [{ name: "EMAIL" }];
  }

  config.secrets = { required: requiredSecrets(options) };

  return `# Generated by \`npm run deploy\` from wrangler.toml. Do not edit.\n\n${stringify(config)}\n`;
}
